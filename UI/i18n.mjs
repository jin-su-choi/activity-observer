// Stored facts and published reports keep the Korean tokens they were written
// with, so their digests stay valid. Display code translates by ID where one
// exists and by token otherwise.
export const locales = ['ko', 'en'];
export const canonicalLocale = 'ko';
export const fallbackLocale = 'en';

// The first recognizable language tag decides. Unsupported languages use English.
export function resolveLocale(...tags) {
  for (const tag of tags.flat()) {
    if (typeof tag !== 'string') continue;
    const language = tag.trim().toLowerCase().split(/[-_.@]/)[0];
    if (locales.includes(language)) return language;
    if (/^[a-z]{2,3}$/.test(language)) return fallbackLocale;
  }
  return fallbackLocale;
}

