// Times are shown in the Mac's time zone, which the server sends with each
// view. Without one, the zone of the device showing the widget is used.
export function createI18n(requested, timeZone) {
  const locale = locales.includes(requested) ? requested : fallbackLocale;
  const tag = intlTags[locale];
  const integerFormat = new Intl.NumberFormat(tag);
  let zoned = options => new Intl.DateTimeFormat(tag, { ...(timeZone && { timeZone }), ...options });
  try { zoned({}); } catch { timeZone = undefined; }
  const clock = zoned({ hour: '2-digit', minute: '2-digit', hourCycle: 'h23' });
  const stampFormat = zoned({ month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' });
  const monthDay = zoned({ month: '2-digit', day: '2-digit' });
  const fullFormat = zoned({ dateStyle: 'medium', timeStyle: 'medium' });
  const isoDay = new Intl.DateTimeFormat('sv-SE', { ...(timeZone && { timeZone }), dateStyle: 'short' });
  const dayFormat = new Intl.DateTimeFormat(tag, { timeZone: 'UTC', dateStyle: 'medium' });
  const zoneId = clock.resolvedOptions().timeZone;
  const zone = zoneNames[zoneId] ?? zoned({ timeZoneName: 'short' }).formatToParts(new Date()).find(part => part.type === 'timeZoneName')?.value ?? zoneId;
  const format = { n: value => integerFormat.format(value), plural: (count, one, other) => count === 1 ? one : other, zone };
  const has = key => Object.hasOwn(messages[locale], key);
  const t = (key, params = {}) => {
    const message = messages[locale][key] ?? messages[canonicalLocale][key];
    if (message === undefined) return key;
    return typeof message === 'function' ? message(params, format) : message;
  };
  const token = (group, text) => {
    const key = tokenIndex[group]?.get(text);
    return key ? tokens[group][key][locale] : text;
  };
  return {
    locale, tag, t, has, token, timeZone: zoneId,
    today: () => isoDay.format(new Date()),
    monthDay: seconds => monthDay.format(new Date(seconds * 1000)),
    integer: format.n,
    decimal: (value, digits = 1) => value.toLocaleString(tag, { maximumFractionDigits: digits }),
    time: seconds => clock.format(new Date(seconds * 1000)),
    stamp: seconds => stampFormat.format(new Date(seconds * 1000)),
    dateTime: seconds => fullFormat.format(new Date(seconds * 1000)),
    day: day => locale === 'ko' ? day.replaceAll('-', '.') : dayFormat.format(new Date(day + 'T00:00:00Z')),
    tokenList: (group, text, separator = ' · ') => typeof text === 'string' ? text.split(separator).map(part => token(group, part)).join(separator) : text,
    programName: (id, name) => {
      const known = tokens.program[id];
      return known && Object.values(known).includes(name) ? known[locale] : name;
    },
    kindLabel: (kind, fallback) => has('kind.' + kind) ? t('kind.' + kind) : fallback ?? kind,
    reason: code => t('incident.reason.' + code),
    error: (code, params) => has('error.' + code) ? t('error.' + code, params) : undefined
  };
}

export function localizeReview(review, i18n) {
  if (!review) return review;
  const label = ['normal', 'attention', 'threat'].includes(review.status) ? i18n.t('status.' + review.status) : review.label;
  return { ...review, label, reason: i18n.token('reviewReason', review.reason) };
}

// Card metrics are stored with their Korean labels. Their IDs select the text.
export function localizeMetric(metric, i18n) {
  const key = 'metric.' + metric.id;
  const text = value => i18n.tokenList('feature', value);
  return { ...metric,
    ...(i18n.has(key + '.label') && { label: i18n.t(key + '.label') }),
    ...(metric.unit !== undefined && i18n.has(key + '.unit') && { unit: i18n.t(key + '.unit') }),
    ...(typeof metric.detail === 'string' && { detail: text(metric.detail) }),
    ...(metric.note?.type === 'text' && { note: { ...metric.note, value: text(metric.note.value) } }) };
}

export function localizeProgramCard(card, i18n) {
  return { ...card, name: i18n.programName(card.id, card.name),
    ...(card.review && { review: localizeReview(card.review, i18n) }),
    ...(Array.isArray(card.metrics) && { metrics: card.metrics.map(metric => localizeMetric(metric, i18n)) }) };
}

export function localizeCardSummary(summary, i18n) {
  return { ...summary, applications: summary.applications?.map(card => localizeProgramCard(card, i18n)) };
}

// Translates the display fields of one program. IDs, kinds, counts, paths and
// event references are returned unchanged.
export function localizeApplication(app, i18n) {
  return { ...localizeProgramCard(app, i18n),
    ...(app.type !== undefined && { type: i18n.token('type', app.type) }),
    ...(app.categories && { categories: Object.fromEntries(Object.entries(app.categories).map(([name, count]) => [i18n.token('category', name), count])) }),
    ...(Array.isArray(app.activity) && { activity: app.activity.map(row => ({ ...row, label: i18n.kindLabel(row.kind, row.label),
      note: i18n.token('note', row.note), category: i18n.token('category', row.category) })) }),
    ...(Array.isArray(app.endpoints) && { endpoints: app.endpoints.map(row => ({ ...row, remote: i18n.token('endpoint', row.remote) })) }) };
}

export function localizeView(view, i18n) {
  return { ...view, apps: view.apps.map(app => localizeApplication(app, i18n)),
    ...(Array.isArray(view.catalog) && { catalog: view.catalog.map(card => localizeProgramCard(card, i18n)) }) };
}

const staticText = [
  ['data-i18n', (element, text) => { element.textContent = text; }],
  ['data-i18n-label', (element, text) => element.setAttribute('aria-label', text)],
  ['data-i18n-placeholder', (element, text) => element.setAttribute('placeholder', text)]
];

// Fills widget markup that carries a message key instead of text.
export function applyStaticText(root, i18n) {
  root.ownerDocument.documentElement.lang = i18n.locale;
  for (const [attribute, apply] of staticText) {
    for (const element of [root, ...root.querySelectorAll('[' + attribute + ']')]) {
      if (element.hasAttribute(attribute)) apply(element, i18n.t(element.getAttribute(attribute)));
    }
  }
}

